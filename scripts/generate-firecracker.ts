// Regenerates only the Firecracker operations hostd uses, from the pinned
// upstream Swagger spec. No runtime dependencies or handwritten API models.
import { createHash } from 'node:crypto'
import { join } from 'node:path'

const version = '1.17.0'
const source = `https://raw.githubusercontent.com/firecracker-microvm/firecracker/v${version}/src/firecracker/swagger/firecracker.yaml`
type Schema = {
  $ref?: string; type?: string; enum?: unknown[]; required?: string[]
  properties?: Record<string, Schema>; items?: Schema; additionalProperties?: boolean | Schema
}
type Operation = { parameters?: { in: string; schema?: Schema }[]; responses: Record<string, { schema?: Schema }> }
type Swagger = { info: { version: string }; definitions: Record<string, Schema>; paths: Record<string, Record<string, Operation>> }
const text = process.argv[2] ? await Bun.file(process.argv[2]).text() : await fetch(source).then((r) => {
  if (!r.ok) throw new Error(`Firecracker spec returned ${r.status}`)
  return r.text()
})
const spec = Bun.YAML.parse(text) as Swagger
if (spec.info.version !== version) throw new Error(`expected Firecracker ${version}`)
const needed = new Set<string>()
function type(schema: Schema): string {
  if (schema.$ref) {
    const name = schema.$ref.replace('#/definitions/', '')
    needed.add(name)
    return name
  }
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ')
  if (schema.type === 'string') return 'string'
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (schema.type === 'boolean') return 'boolean'
  if (schema.type === 'array' && schema.items) return `Array<${type(schema.items)}>`
  if (schema.properties) return `{ ${Object.entries(schema.properties).map(([key, value]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${type(value)}`).join('; ')} }`
  if (schema.additionalProperties) return `Record<string, ${schema.additionalProperties === true ? 'unknown' : type(schema.additionalProperties)}>`
  throw new Error(`unsupported schema: ${JSON.stringify(schema)}`)
}
// A third element names the concrete path hostd calls for a templated one.
const calls: [string, string, string?][] = [
  ['GET', '/'], ['PATCH', '/vm'], ['PUT', '/snapshot/create'], ['PUT', '/snapshot/load'], ['PUT', '/mmds'],
  ['PATCH', '/drives/{drive_id}', '/drives/rootfs'],
]
const operations = calls.map(([method, path, concrete = path]) => {
  const operation = spec.paths[path]?.[method.toLowerCase()]
  if (!operation) throw new Error(`missing ${method} ${path}`)
  const body = operation.parameters?.find((p) => p.in === 'body')?.schema
  const response = operation.responses['200']?.schema
  return `  '${method} ${concrete}': { body: ${body ? type(body) : 'undefined'}; response: ${response ? type(response) : 'void'} }`
})
const definitions: string[] = []
// Set iteration includes references added while visiting a definition.
for (const name of needed) {
  const schema = spec.definitions[name]
  if (!schema) throw new Error(`missing definition ${name}`)
  definitions.push(`export type ${name} = ${type(schema)}`)
}
const generated = `// Generated by scripts/generate-firecracker.ts. Do not edit.\n// Source: ${source}\n// SHA-256: ${createHash('sha256').update(text).digest('hex')}\n\n${definitions.join('\n')}\n\nexport type FirecrackerApi = {\n${operations.join('\n')}\n}\n`
await Bun.write(join(import.meta.dir, '../apps/hostd/src/generated/firecracker.ts'), generated)
